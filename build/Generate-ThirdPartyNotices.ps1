<#
.SYNOPSIS
    Regenerates THIRD_PARTY_NOTICES.md from the NuGet packages the app actually ships.

.DESCRIPTION
    Reads SyteQuery.Desktop/obj/project.assets.json (run `dotnet restore` first), looks up each
    package's license in its .nuspec, and writes a table plus the full text of any license that
    isn't a standard SPDX one (Ms-PL for AvalonDock). Run it again whenever packages change.
#>
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$assetsPath = Join-Path $root 'SyteQuery.Desktop\obj\project.assets.json'
if (-not (Test-Path $assetsPath)) { throw "Run 'dotnet restore SyteQuery.Desktop' first." }

$assets = Get-Content $assetsPath -Raw | ConvertFrom-Json
$pkgRoot = if ($env:NUGET_PACKAGES) { $env:NUGET_PACKAGES } else { Join-Path $env:USERPROFILE '.nuget\packages' }
$targetKey = $assets.targets.PSObject.Properties.Name | Where-Object { $_ -match 'net9.0-windows' } | Select-Object -First 1
# "Direct" = packages either project references itself (Desktop and Core), as opposed to transitive ones.
$direct = foreach ($proj in 'SyteQuery.Desktop', 'SyteQuery.Core') {
    $a = Get-Content (Join-Path $root "$proj\obj\project.assets.json") -Raw | ConvertFrom-Json
    $a.projectFileDependencyGroups.PSObject.Properties.Value | ForEach-Object { $_ -replace ' >=.*', '' }
}

$rows = foreach ($entry in $assets.targets.$targetKey.PSObject.Properties) {
    if ($entry.Value.type -ne 'package') { continue }
    $id, $ver = $entry.Name -split '/'
    $dir = Join-Path $pkgRoot "$($id.ToLower())\$ver"
    $nuspec = Join-Path $dir "$($id.ToLower()).nuspec"
    $license = '(see package)'; $url = ''; $licenseFileText = $null
    if (Test-Path $nuspec) {
        [xml]$x = Get-Content $nuspec -Raw
        $m = $x.package.metadata
        $url = $m.projectUrl
        if ($m.license -and $m.license.type -eq 'expression') { $license = $m.license.'#text' }
        elseif ($m.license -and $m.license.type -eq 'file') {
            $f = Join-Path $dir $m.license.'#text'
            if (Test-Path $f) {
                $licenseFileText = (Get-Content $f -Raw).Trim()
                $license = if ($licenseFileText -match 'Ms-PL|Microsoft Public License') { 'Ms-PL' } else { 'see license text below' }
            }
        }
        elseif ($m.licenseUrl) { $license = $m.licenseUrl }
    }
    [pscustomobject]@{ Id = $id; Version = $ver; License = $license; Url = $url; Text = $licenseFileText; Direct = ($direct -contains $id) }
}
$rows = $rows | Sort-Object Id

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('# Third-party notices')
[void]$sb.AppendLine()
[void]$sb.AppendLine('SyteQuery is MIT licensed (see [LICENSE](LICENSE)). It is built on the open-source packages below, each under its own license. This file is generated by `build/Generate-ThirdPartyNotices.ps1` from the packages the app actually ships.')
[void]$sb.AppendLine()
[void]$sb.AppendLine('## Direct dependencies')
[void]$sb.AppendLine()
[void]$sb.AppendLine('| Package | Version | License | Project |')
[void]$sb.AppendLine('|---|---|---|---|')
foreach ($r in $rows | Where-Object Direct) { [void]$sb.AppendLine("| $($r.Id) | $($r.Version) | $($r.License) | $($r.Url) |") }
[void]$sb.AppendLine()
[void]$sb.AppendLine('## All packages (including transitive)')
[void]$sb.AppendLine()
[void]$sb.AppendLine('| Package | Version | License |')
[void]$sb.AppendLine('|---|---|---|')
foreach ($r in $rows) { [void]$sb.AppendLine("| $($r.Id) | $($r.Version) | $($r.License) |") }
[void]$sb.AppendLine()
[void]$sb.AppendLine('License identifiers are [SPDX](https://spdx.org/licenses/) names; the full text of MIT and Apache-2.0 is at that site and in each package.')

$texts = $rows | Where-Object { $_.Text } | Group-Object License
foreach ($g in $texts) {
    [void]$sb.AppendLine()
    [void]$sb.AppendLine("## $($g.Name) license text")
    [void]$sb.AppendLine()
    [void]$sb.AppendLine("Applies to: $((($g.Group | ForEach-Object { $_.Id }) -join ', '))")
    [void]$sb.AppendLine()
    [void]$sb.AppendLine('```text')
    [void]$sb.AppendLine($g.Group[0].Text)
    [void]$sb.AppendLine('```')
}

$out = Join-Path $root 'THIRD_PARTY_NOTICES.md'
Set-Content -Path $out -Value $sb.ToString() -Encoding UTF8
Write-Host "Wrote $out ($($rows.Count) packages)"
